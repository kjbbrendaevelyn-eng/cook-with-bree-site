import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(root, "content");

function slugsIn(subdir) {
  const dir = path.join(contentDir, subdir);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((file) => file.endsWith(".md"))
    .map((file) => file.replace(/\.md$/, ""))
    .sort();
}

const recipes = slugsIn("recipes");
const stories = slugsIn("stories");

const outPath = path.join(root, "src/lib/content-manifest.ts");
const source = `/** Auto-generated by scripts/generate-content-manifest.mjs — do not edit by hand. */
export const contentManifest = {
  recipes: ${JSON.stringify(recipes, null, 2)},
  stories: ${JSON.stringify(stories, null, 2)},
} as const;
`;

fs.writeFileSync(outPath, source);
console.log(
  `Wrote content manifest (${recipes.length} recipes, ${stories.length} stories)`
);
